public class Avg {
    public static void main(String[] args) {

        // Calculate the average of three numbers.

        int num1 = 10;
        int num2 = 20;
        int num3 = 30;

        int average = (num1 + num2 + num3) / 3;
        System.out.println("The average is : " + average);
    }
}
