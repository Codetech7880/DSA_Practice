package Intro.Operators;

public class Terniry {
    public static void main(String[] args) {
        
        int num1 = 10;
        int num2 = 20;

        // Terniary operator helps to minimize the if-else statement.
        // Synatx : (( Condition ) ? true : false);
        System.out.println((num1 > num2) ? "greater" : "smaller");
        
    }
}
