package Intro.Operators;

public class Relational {
    public static void main(String[] args) {
        
        int num1 = 10;
        int num2 = 20;

        // Greater than operator helps us to find the greater number between two numbers.
        System.out.println("Greater than operator : "+ (num1 > num2));

        // Smaller than operator helps us to find the smaller number between two numbers.
        System.out.println("Smaller than operator : "+ (num1 < num2));

        // >= This operator checks whether the number is greater or equal
        System.out.println("Greater than or equals to operator : "+ (num1 >= num2));

        // <= This operator checks whether the number is smaller or equal
        System.out.println("Smaller than or equals to operator : "+ (num1 > num2));

        // This "==" operator help us to find out whether these numbers are equal.
        System.out.println("Equals to operator : "+ (num1 == num2));

        // This "!=" operator help us to find out whether these numbers are unequal.
        System.out.println("NotEquals to operator : "+ (num1 != num2));

    }
}
