package Intro.Operators;

public class Arithematic {
    
    public static void main(String[] args){
        
        int a = 20;
        int b = 5;

        // + Operator is used for addition of two numbers.
        int add = a + b;

        // - Operator is used to subtraction between two numbers.
        int sub = a - b;

        // * Operator is used for multiplication of two numbers.
        int mul = a * b;

        // / Operator is used for division of two numbers.
        int div = a / b;

        // % Modulus Operator is used for finding the reminder of a particular number.
        int mod = a % b;

        System.out.println("The addition of two number is : "+ add);
        System.out.println("The subtraction of two number is : "+ sub);
        System.out.println("The multiplication of two number is : "+ mul);
        System.out.println("The division of two number is : "+ div);
        System.out.println("The modulus of two number is : "+ mod);

    }

}
